/**
 * Normalizes query string and resolves country / city aliases
 */
export function matchesLocationQuery(loc: GlobalLocation, query: string): boolean {
  if (!query) return true;
  const q = query.trim().toLowerCase();
  
  if (loc.city.toLowerCase().includes(q)) return true;
  if (loc.code.toLowerCase().includes(q)) return true;
  if (loc.country.toLowerCase().includes(q)) return true;
  if (loc.region.toLowerCase().includes(q)) return true;
  if (loc.airportName.toLowerCase().includes(q)) return true;
  if (loc.airportCode.toLowerCase().includes(q)) return true;
  if (loc.seaportName.toLowerCase().includes(q)) return true;
  if (loc.seaportCode.toLowerCase().includes(q)) return true;

  if (loc.aliases && loc.aliases.some((a) => a.toLowerCase().includes(q) || q.includes(a.toLowerCase()))) {
    return true;
  }

  // Common spelling and acronym synonyms
  if ((q === 'us' || q === 'usa' || q === 'america' || q === 'united states') && loc.country === 'United States') return true;
  if ((q === 'uk' || q === 'britain' || q === 'great britain' || q === 'england' || q === 'united kingdom') && loc.country === 'United Kingdom') return true;
  if ((q === 'uae' || q === 'emirates' || q === 'united arab emirates') && loc.country === 'United Arab Emirates') return true;
  if ((q === 'ksa' || q === 'saudi' || q === 'saudi arabia') && loc.country === 'Saudi Arabia') return true;
  if ((q === 'korea' || q === 'south korea') && loc.country === 'South Korea') return true;
  if ((q === 'vietnam' || q === 'viet nam') && loc.country === 'Vietnam') return true;

  return false;
}
